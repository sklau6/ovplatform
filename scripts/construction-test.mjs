import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox','--hide-scrollbars'] })
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto('http://127.0.0.1:4310/#/construction', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(4500)
await page.getByRole('button', { name: /Mobilise/ }).click()
await page.waitForTimeout(2600)
await page.screenshot({ path: '.shots/construction-mobilise.png' })
await page.getByRole('button', { name: /Fit-out & handover/ }).click()
await page.waitForTimeout(3000)
await page.screenshot({ path: '.shots/construction-fitout.png' })
await page.getByText('Drone scan', { exact: true }).click()
await page.waitForTimeout(2000)
await page.screenshot({ path: '.shots/construction-scan.png' })
console.log(JSON.stringify({ errors: errors.slice(0, 8) }, null, 2))
await browser.close()
