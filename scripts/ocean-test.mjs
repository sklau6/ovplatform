import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox','--hide-scrollbars'] })
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto('http://127.0.0.1:4310/#/esg-building', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6500)
await page.getByRole('button', { name: /Water/ }).first().click()
await page.waitForTimeout(900)
await page.getByRole('button', { name: /Net zero/ }).click()
await page.waitForTimeout(1000)
await page.screenshot({ path: '.shots/esgb-netzero.png' })
await page.getByRole('button', { name: /Switch to light theme/ }).click()
await page.waitForTimeout(700)
await page.screenshot({ path: '.shots/esgb-light.png' })
await page.goto('http://127.0.0.1:4310/#/dc-ops', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6000)
await page.getByRole('button', { name: /Maintenance/i }).click()
await page.waitForTimeout(900)
await page.screenshot({ path: '.shots/dcops-maintenance.png' })
console.log(JSON.stringify({ errors: errors.slice(0, 8), theme: await page.evaluate(() => document.documentElement.dataset.theme) }, null, 2))
await page.close()
for (const [path, name] of [['#/esg-building','esgb'], ['#/dc-ops','dcops']]) {
  const m = await browser.newPage({ viewport: { width: 390, height: 844 } })
  await m.goto('http://127.0.0.1:4310/' + path, { waitUntil: 'domcontentloaded' })
  await m.waitForTimeout(5500)
  await m.screenshot({ path: `.shots/${name}-mobile.png` })
  console.log(name, await m.evaluate(() => ({ w: document.documentElement.scrollWidth, vw: innerWidth })))
  await m.close()
}
await browser.close()
