import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox','--hide-scrollbars'] })
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto('http://127.0.0.1:4310/#/energy', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(7000)
await page.getByRole('button', { name: /Island mode/ }).first().click()
await page.waitForTimeout(1800)
await page.screenshot({ path: '.shots/energy-island.png' })
const body = await page.locator('body').innerText()
await page.getByRole('button', { name: /Switch to light theme/ }).click()
await page.waitForTimeout(900)
await page.screenshot({ path: '.shots/energy-light.png' })
console.log(JSON.stringify({ errors: errors.slice(0, 6), island: body.includes('islanded'), frequency: body.includes('49.92') }, null, 2))
await page.close()
const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } })
await mobile.goto('http://127.0.0.1:4310/#/energy', { waitUntil: 'domcontentloaded' })
await mobile.waitForTimeout(6000)
await mobile.screenshot({ path: '.shots/energy-mobile.png' })
