import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox','--hide-scrollbars'] })
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto('http://127.0.0.1:4310/#/proptech', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6000)
await page.getByText('Occupancy', { exact: true }).first().click()
await page.waitForTimeout(2000)
await page.screenshot({ path: '.shots/proptech-occupancy.png' })
await page.getByText('Explode stack', { exact: true }).click()
await page.waitForTimeout(5000)
await page.screenshot({ path: '.shots/proptech-exploded.png' })
// click the L09 row in the floor stack to verify selection
await page.getByRole('button', { name: /09 0%|09/ }).first().click().catch(() => {})
await page.waitForTimeout(1500)
await page.screenshot({ path: '.shots/proptech-select.png' })
console.log(JSON.stringify({ errors: errors.slice(0, 8) }, null, 2))
await browser.close()
