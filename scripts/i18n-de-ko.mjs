import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
await page.goto('http://127.0.0.1:4310/#/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1500)
const langButton = page.getByRole('button', { name: /Language|语言|語言/i })
await langButton.click()
const langs = await page.locator('.pref-popover button').allTextContents()
await page.getByRole('button', { name: /Deutsch/ }).click()
await page.waitForTimeout(600)
const de = await page.evaluate(() => ({ lang: document.documentElement.lang, h1: document.querySelector('main h1')?.textContent }))
await page.getByRole('button', { name: /Language|Sprache/i }).click()
await page.getByRole('button', { name: /한국어/ }).click()
await page.waitForTimeout(600)
const ko = await page.evaluate(() => ({ lang: document.documentElement.lang, h1: document.querySelector('main h1')?.textContent }))
console.log(JSON.stringify({ langs, de, ko }, null, 2))
await browser.close()
