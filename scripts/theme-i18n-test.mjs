import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox','--hide-scrollbars'] })
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto('http://127.0.0.1:4310/#/construction', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(7000)
await page.getByRole('button', { name: 'Switch to light theme' }).click()
await page.waitForTimeout(1500)
await page.screenshot({ path: '.shots/construction-light.png' })
await page.getByRole('button', { name: 'Light' }).count().catch(()=>{})
await page.getByRole('button', { name: 'Language' }).click()
await page.waitForTimeout(300)
await page.getByRole('button', { name: /繁體中文/ }).click()
await page.waitForTimeout(1500)
await page.screenshot({ path: '.shots/construction-light-zh.png' })
console.log(JSON.stringify({ errors: errors.slice(0, 8), lang: await page.evaluate(() => document.documentElement.lang), theme: await page.evaluate(() => document.documentElement.dataset.theme) }, null, 2))
await browser.close()
