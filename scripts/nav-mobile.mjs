import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox','--hide-scrollbars'] })
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
await page.goto('http://127.0.0.1:4320/#/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(1500)
const before = await page.evaluate(() => ({ w: document.documentElement.scrollWidth, sidebar: document.querySelector('.app-sidebar')?.getBoundingClientRect().x }))
await page.getByRole('banner').getByRole('button', { name: 'Open navigation' }).click()
await page.waitForTimeout(700)
const open = await page.evaluate(() => document.querySelector('.app-sidebar')?.getBoundingClientRect().x)
await page.getByRole('button', { name: 'Close navigation' }).click()
await page.waitForTimeout(700)
const closed = await page.evaluate(() => document.querySelector('.app-sidebar')?.getBoundingClientRect().x)
console.log({ before, open, closed, w: (await page.evaluate(() => document.documentElement.scrollWidth)) })
await browser.close()
