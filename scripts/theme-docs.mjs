import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox','--hide-scrollbars'] })
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
await page.addInitScript(() => { localStorage.setItem('ophylla-theme', 'light'); localStorage.setItem('ophylla-locale', 'en') })
await page.goto('http://127.0.0.1:4310/#/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(3000)
await page.screenshot({ path: 'docs/light-command-center.png' })
await page.addInitScript(() => {})
await page.evaluate(() => localStorage.setItem('ophylla-locale', 'zh-Hans'))
await page.goto('http://127.0.0.1:4310/#/construction', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(7000)
await page.screenshot({ path: 'docs/chinese-light.png' })
await page.evaluate(() => { localStorage.setItem('ophylla-theme', 'dark'); localStorage.setItem('ophylla-locale', 'en') })
await page.goto('http://127.0.0.1:4310/#/twin', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6500)
await page.getByRole('button', { name: 'Typhoon', exact: true }).click()
await page.waitForTimeout(2500)
await page.screenshot({ path: 'docs/typhoon-twin.png' })
await browser.close()
